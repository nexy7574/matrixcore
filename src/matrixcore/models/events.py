class ClientEventWithoutRoomID(BaseModel):
    """
    The format used for events when they are returned from a homeserver to a client via the Client-Server API,
    or sent to an Application Service via the Application Services API.
    """

    class UnsignedData(BaseModel):
        age: int = None
        """
        The time in milliseconds that has elapsed since the event was sent. 
        This field is generated by the local homeserver, and may be incorrect if the local time on at least one of the
        two servers is out of sync, which can cause the age to either be negative or greater than it actually is.
        """
        membership: str = None
        """The room membership of the user making the request, at the time of the event. Generally not used."""
        prev_content: dict[str, typing.Any] = None
        """
        The previous content for this event
        This field is generated by the local homeserver, and is only returned if the event is a state event,
        and the client has permission to see the previous content.
        """
        redacted_because: typing.Union["ClientEventWithoutRoomID", "ClientEvent"] = None
        """The event that redacted this one, if any."""
        transaction_id: str = None
        """The client-supplied transaction ID, if the client being given the event is the same one which sent it."""
        replaces_state: str = None
        """The event ID of the previous state of this state event."""

    content: dict[str, typing.Any]
    """The body of this event, as created by the client which sent it."""
    event_id: str
    """The globally unique identifier for this event."""
    origin_server_ts: int
    """Timestamp (in milliseconds since the unix epoch) on originating homeserver when this event was sent."""
    sender: str
    """Contains the fully-qualified ID of the user who sent this event."""
    state_key: str = None
    """
    Present if, and only if, this event is a state event. The key making this piece of state unique in the room.
    Note that it is often an empty string.

    State keys starting with an @ are reserved for referencing user IDs, such as room members. 
    With the exception of a few events, state events set with a given user’s ID as the state key MUST only be set by
    that user.
    """
    type: str
    """the type of the event."""
    unsigned: UnsignedData = None
    """Contains optional extra information about the event."""

    def __hash__(self):
        return hash((self.event_id, self.type, self.state_key or ''))

    def __eq__(self, other):
        return hasattr(other, "event_id") and self.event_id == other.event_id


class ClientEvent(ClientEventWithoutRoomID):
    """
    The format used for events when they are returned from a homeserver to a client via the Client-Server API,
    or sent to an Application Service via the Application Services API.
    """

    room_id: str
    """The ID of the room associated with this event."""

    def __hash__(self):
        return hash((self.event_id, self.type, self.state_key or '', self.room_id))

    def __eq__(self, other):
        return (
            hasattr(other, "event_id") and self.event_id == other.event_id
            and hasattr(other, "room_id") and self.room_id == other.room_id
        )


class StrippedStateEvent(BaseModel):
    """
    A stripped-down version of the Event format, primarily used for sending state events to clients.

    See: https://spec.matrix.org/v1.13/client-server-api/#stripped-state
    """

    content: dict[
        str,
        typing.Union[
            "MRoomCreate",
            "MRoomName",
            "MRoomAvatar",
            "MRoomTopic",
            "MRoomJoinRules",
            "MRoomCanonicalAlias",
            "MRoomEncryption",
        ],
    ]
    """The content of the event."""
    sender: str
    """The user ID of the sender of the event."""
    state_key: str
    """
    A key which defines the state type of the event. For example, a key of 'foo' would represent a state event of type
    'm.room.state.foo'.
    """
    type: str
    """The type of the event."""

    def __hash__(self):
        return hash((self.type, self.state_key))

    def __eq__(self, other):
        return (
            hasattr(other, "type") and self.type == other.type
            and hasattr(other, "state_key") and self.state_key == other.state_key
            and hasattr(other, "content") and other.content == self.content
        )


class MRoomCreate(BaseModel):
    """Represents the body of an m.room.create event"""

    creator: str = None
    """
    The user_id of the room creator.
    Required for, and only present in, room versions 1 - 10.
    Starting with room version 11 the event sender should be used instead.
    """
    federate: bool = Field(default=True, alias="m.federate")
    """Whether users on other homeservers are allowed to join this room."""
    predecessor: RoomPredecessor = None
    """A reference to the room that this room replaces, if the previous room was upgraded."""
    room_version: str = "1"  # mfw default is an insecure version
    """The version of the room. Defaults to "1"."""
    type: str = None
    """
    Optional room type to denote a room’s intended function outside of traditional conversation.
    
    Unspecified room types are possible using Namespaced Identifiers.
    """


class MRoomJoinRules(BaseModel):
    """Represents the body of an m.room.join_rules event"""

    class AllowCondition(BaseModel):
        room_id: str = None
        """
        Required if type is m.room_membership. The room ID to check the user’s membership against.
        If the user is joined to this room, they satisfy the condition and thus are permitted to join the restricted
        room.
        """
        type: typing.Literal["m.room_membership"]
        """The type of event to allow. This should be m.room_membership."""

    allow: list[AllowCondition] = None
    """A list of allow conditions required to join."""
    join_rule: typing.Literal["public", "knock", "invite", "restricted", "knock_restricted", "private"]
    """The join rule"""


