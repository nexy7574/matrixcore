class MRoomMember(BaseModel):
    """Represents the body of an m.room.member event"""

    class ThirdPartyInvite(BaseModel):
        display_name: str

        class Signed(BaseModel):
            mxid: str
            signatures: dict[str, dict[str, str]]
            token: str

    membership: typing.Literal["join", "leave", "ban", "invite", "knock"]
    displayname: str | None = None
    avatar_url: MXCUri = None
    is_direct: bool = None
    join_authorised_via_users_server: str = None
    """
    Usually found on join events, this field is used to denote which homeserver
    (through representation of a user with sufficient power level) authorised the user’s join.
    More information about this field can be found in the Restricted Rooms Specification.

    Client and server implementations should be aware of the signing implications of including this field in further
    events: in particular, the event must be signed by the server which owns the user ID in the field.
    When copying the membership event’s content (for profile updates and similar) it is therefore encouraged
    to exclude this field in the copy, as otherwise the event might fail event authorization.
    """
    third_party_invite: ThirdPartyInvite = None
    reason: str | None = None


class MRoomPowerLevels(BaseModel):
    """Represents the power levels for a room."""

    # This event specifies the minimum level a user must have in order to perform a certain action.
    # It also specifies the levels of each user in the room.
    #
    # If a user_id is in the users list, then that user_id has the associated power level.
    # Otherwise they have the default level users_default. If users_default is not supplied, it is assumed to be 0.
    # If the room contains no m.room.power_levels event, the room’s creator has a power level of 100,
    # and all other users have a power level of 0.
    #
    # The level required to send a certain event is governed by events, state_default and events_default.
    # If an event type is specified in events, then the user must have at least the level specified in order to send
    # that event. If the event type is not supplied, it defaults to events_default for Message Events and state_default
    # for State Events.
    #
    # If there is no state_default in the m.room.power_levels event, or there is no m.room.power_levels event,
    # the state_default is 50. If there is no events_default in the m.room.power_levels event, or there is no
    # m.room.power_levels event, the events_default is 0.
    #
    # The power level required to invite a user to the room, kick a user from the room, ban a user from the room,
    # or redact an event sent by another user, is defined by invite, kick, ban, and redact, respectively.
    # The levels for kick, ban and redact default to 50 if they are not specified in the m.room.power_levels event,
    # or if the room contains no m.room.power_levels event. invite defaults to 0 in either case.
    #
    # Note:
    #
    # The allowed range for power level values is [-(2**53)+1, (2**53)-1], as required by the Canonical JSON
    # specification.
    __MAX_VALUE = (2**53) - 1
    __MIN_VALUE = -(2**53) + 1

    events_default: int = Field(0, ge=__MIN_VALUE, le=__MAX_VALUE)
    state_default: int = Field(50, ge=__MIN_VALUE, le=__MAX_VALUE)
    users_default: int = Field(0, ge=__MIN_VALUE, le=__MAX_VALUE)
    invite: int = Field(0, ge=__MIN_VALUE, le=__MAX_VALUE)
    kick: int = Field(50, ge=__MIN_VALUE, le=__MAX_VALUE)
    ban: int = Field(default=50, ge=__MIN_VALUE, le=__MAX_VALUE)
    """The level required to ban a user."""
    redact: int = Field(50, ge=__MIN_VALUE, le=__MAX_VALUE)
    """The level required to redact an event sent by another user."""

    # v For some reason, PyCharm complains about the default value being mutable, even though it isn't.
    # noinspection PyDataclass
    notifications: dict[typing.Literal["room"] | str, int] = Field(default_factory=lambda: {"room": 50})
    """
    The power level requirements for specific notification types.
    This is a mapping from key to power level for that notifications key.
    """
    # noinspection PyDataclass
    users: dict[str, int] = Field(default_factory=dict)
    """The power levels for specific users. This is a mapping from user_id to power level for that user."""
    # noinspection PyDataclass
    events: dict[str, int] = Field(default_factory=dict)
    """The level required to send specific event types. This is a mapping from event type to power level required."""

    def get_user_power_level(self, user_id: str) -> int:
        """
        Gets the power level of the given user.
        """
        return self.users.get(user_id, self.users_default)

    def get_event_power_level(self, event: str) -> int:
        """
        Gets the power level required to send the given event.
        """
        return self.events.get(event, self.events_default)

    def get_state_event_power_level(self, event: str) -> int:
        """
        Gets the power level required to send the given state event.
        """
        return self.events.get(event, self.state_default)

    def get_notification_power_level(self, notification: str) -> int:
        """
        Gets the power level required to send the given notification.
        """
        # The spec doesn't actually define what the default PL for notifications should be,
        # but room defaults to 50, so we'll assume all other unspecified ones do too.
        return self.notifications.get(notification, 50)

    def user_can_send_event(self, user_id: str, event: str) -> bool:
        """
        Checks the power levels to see if the given user id can send the supplied event.

        State events should use get_state_event_power_level instead.
        """
        user_pl = self.get_user_power_level(user_id)
        match event:
            case "ban":
                target_pl = self.ban
            case "kick":
                target_pl = self.kick
            case "redact":
                target_pl = self.redact
            case "invite":
                target_pl = self.invite
            case _:
                target_pl = self.get_event_power_level(event)

        return user_pl >= target_pl

    def user_can_send_state_event(self, user_id: str, event: str) -> bool:
        """
        Checks the power levels to see if the given user id can send the supplied state event.
        """
        user_pl = self.get_user_power_level(user_id)
        target_pl = self.get_state_event_power_level(event)
        return user_pl >= target_pl

    def user_can_redact_event(self, user_id: str, sender: str = None) -> bool:
        """
        Checks if the user can redact an event, optionally by another user.
        """
        if sender:
            return self.user_can_send_event(user_id, "m.room.redact")
        return self.get_user_power_level(user_id) >= self.redact

    def user_can_send_notification(self, user_id: str, notification_type: str) -> bool:
        """
        Checks if the user can send the given notification type.
        """
        return self.get_user_power_level(user_id) >= self.get_notification_power_level(notification_type)
